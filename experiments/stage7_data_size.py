"""
Stage 7 -- Experiment With Training Data

Research question:
    How does the SIZE of the training set affect prediction accuracy?

Experimental design (this is what makes it an experiment and not a demo):

  Independent variable : number of training rows (100 ... 10,000)
  Dependent variable   : test RMSE for x and for y
  Controlled           : the test set (one fixed set of rows, split off once,
                         never trained on), the feature set, the model type
                         and all model hyperparameters.

  Each training size is repeated with several different random draws, because
  a single 100-row training set is one lucky or unlucky sample. We report the
  mean and the spread over those repeats.

Run from anywhere:  python experiments/stage7_data_size.py
"""

import sys
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.linear_model import LinearRegression
from sklearn.ensemble import RandomForestRegressor
from sklearn.metrics import mean_squared_error

ROOT = Path(__file__).resolve().parent.parent
sys.path.append(str(ROOT))

from data.generation.projectileDataGeneration import generateProjectileDataset
from plots.learning_curve import (
    plot_learning_curve,
    plot_stability,
    plot_trajectory_by_datasize,
)

g = 9.81

FEATURES = ["v0", "theta", "y0", "t"]
TARGETS = ["x", "y"]

TRAIN_SIZES = [100, 500, 1000, 5000, 10000]
REPEATS = 5
TEST_ROWS = 4000

# Trajectory reconstruction check: which sizes to draw, and how many unseen
# launch conditions to average the error over.
SWEEP_SIZES = [100, 1000, 10000]
SWEEP_CONDITIONS = 40

# Stages 3-6 use a 2,000-row dataset, which is far too small to train on
# 10,000 rows AND still hold out an untouched test set. Stage 7 therefore uses
# its own larger dataset, generated by the same simulator with a different seed.
DATASET_ROWS = 20000
DATASET_SEED = 7
DATASET_PATH = ROOT / "data" / "projectile_dataset_large.csv"

RESULTS_DIR = ROOT / "results"
FOREST_KWARGS = {"n_estimators": 100, "random_state": 42}


# -------------------- DATA --------------------

def load_dataset():
    """Load the large Stage 7 dataset, generating it once if it is missing."""
    if not DATASET_PATH.exists():
        print(f"Generating {DATASET_ROWS:,}-row dataset -> {DATASET_PATH.name}")
        dataset = generateProjectileDataset(DATASET_ROWS, seed=DATASET_SEED)
        dataset.to_csv(DATASET_PATH, index=False)
    return pd.read_csv(DATASET_PATH)


def rmse(y_true, y_pred):
    return np.sqrt(mean_squared_error(y_true, y_pred))


def make_models():
    """Fresh, untrained models -- identical settings at every training size."""
    return {
        "linear": LinearRegression(),
        "forest": RandomForestRegressor(**FOREST_KWARGS),
    }


# -------------------- EXPERIMENT --------------------

def run_experiment(pool, X_test, y_test):
    """
    Train every model on every training size, REPEATS times each, and
    evaluate all of them on the one fixed test set.
    """
    rows = []

    for n_train in TRAIN_SIZES:
        for repeat in range(REPEATS):
            # a different random draw each repeat, but reproducible
            train = pool.sample(n=n_train, random_state=1000 * repeat + n_train)
            X_train, y_train = train[FEATURES], train[TARGETS]

            for name, model in make_models().items():
                model.fit(X_train, y_train)
                predictions = model.predict(X_test)

                rows.append({
                    "n_train": n_train,
                    "repeat": repeat,
                    "model": name,
                    "rmse_x": rmse(y_test["x"], predictions[:, 0]),
                    "rmse_y": rmse(y_test["y"], predictions[:, 1]),
                })

        print(f"  n_train = {n_train:>6,} done ({REPEATS} repeats x 2 models)")

    return pd.DataFrame(rows)


def summarise(results):
    """Mean and standard deviation of RMSE across the repeats."""
    summary = (
        results
        .groupby(["model", "n_train"])[["rmse_x", "rmse_y"]]
        .agg(["mean", "std"])
        .reset_index()
    )
    # flatten the MultiIndex columns: ('rmse_x', 'mean') -> 'rmse_x_mean'
    summary.columns = [
        col[0] if not col[1] else f"{col[0]}_{col[1]}" for col in summary.columns
    ]
    return summary


# -------------------- PHYSICAL VIEW OF THE SAME RESULT --------------------

def classical_trajectory(v0, theta, y0, t_array):
    x = v0 * np.cos(theta) * t_array
    y = y0 + v0 * np.sin(theta) * t_array - 0.5 * g * t_array**2
    return x, y


def trajectory_error(model, condition, n_points=50):
    """
    Ask a trained model to reconstruct one whole trajectory it never saw, and
    return the mean radial error |predicted - true| along that trajectory,
    together with the sweep itself.
    """
    v0, theta, y0 = condition["v0"], condition["theta"], condition["y0"]

    time_of_flight = (
        v0 * np.sin(theta)
        + np.sqrt((v0 * np.sin(theta)) ** 2 + 2 * g * y0)
    ) / g
    t_sweep = np.linspace(0, time_of_flight, n_points)

    sweep_features = pd.DataFrame({
        "v0": v0, "theta": theta, "y0": y0, "t": t_sweep
    })
    predictions = model.predict(sweep_features)

    x_true, y_true = classical_trajectory(v0, theta, y0, t_sweep)
    radial_error = np.hypot(predictions[:, 0] - x_true, predictions[:, 1] - y_true)

    return predictions, radial_error.mean(), (x_true, y_true)


def trajectory_experiment(pool, test):
    """
    Train one Random Forest per training size, then measure how well each one
    reconstructs entire trajectories for unseen launch conditions.

    Returns the sweeps for a single representative condition (for the visual
    panel) and the error curve averaged over many conditions (for the claim).
    """
    # A representative rather than cherry-picked condition: the held-out row
    # whose launch speed is closest to the median of the test set.
    representative = test.iloc[(test["v0"] - test["v0"].median()).abs().argmin()]
    conditions = test.sample(n=SWEEP_CONDITIONS, random_state=3)

    sweeps = []
    error_rows = []

    for n_train in TRAIN_SIZES:
        train = pool.sample(n=n_train, random_state=n_train)  # the repeat-0 draw
        model = RandomForestRegressor(**FOREST_KWARGS)
        model.fit(train[FEATURES], train[TARGETS])

        predictions, _, truth = trajectory_error(model, representative)
        if n_train in SWEEP_SIZES:
            sweeps.append((n_train, predictions))

        errors = np.array([
            trajectory_error(model, condition)[1]
            for _, condition in conditions.iterrows()
        ])
        error_rows.append({
            "n_train": n_train,
            "mean_error": errors.mean(),
            "q25_error": np.percentile(errors, 25),
            "q75_error": np.percentile(errors, 75),
        })

    x_classical, y_classical = truth
    return representative, x_classical, y_classical, sweeps, pd.DataFrame(error_rows)


# -------------------- MAIN --------------------

if __name__ == "__main__":

    dataset = load_dataset()

    # Split ONCE, before anything else. `test` is the same set of rows for
    # every model trained below -- otherwise we would be changing two things
    # at once and could not attribute a change in RMSE to the training size.
    pool, test = train_test_split(dataset, test_size=TEST_ROWS, random_state=42)
    X_test, y_test = test[FEATURES], test[TARGETS]

    print("=" * 60)
    print("STAGE 7 -- EFFECT OF TRAINING-SET SIZE")
    print("=" * 60)
    print(f"Dataset      : {len(dataset):,} rows ({DATASET_PATH.name})")
    print(f"Training pool: {len(pool):,} rows")
    print(f"Fixed test   : {len(test):,} rows (never trained on)")
    print(f"Sizes        : {TRAIN_SIZES}, {REPEATS} repeats each\n")

    results = run_experiment(pool, X_test, y_test)
    results.to_csv(RESULTS_DIR / "stage7_learning_curve.csv", index=False)

    summary = summarise(results)
    summary.to_csv(RESULTS_DIR / "stage7_learning_curve_summary.csv", index=False)

    print("\n--- mean +/- std of test RMSE over repeats ---")
    for model in ["linear", "forest"]:
        print(f"\n{model}")
        rows = summary[summary["model"] == model].sort_values("n_train")
        for _, r in rows.iterrows():
            print(
                f"  n={int(r['n_train']):>6,}  "
                f"RMSE_x = {r['rmse_x_mean']:8.3f} +/- {r['rmse_x_std']:6.3f} m   "
                f"RMSE_y = {r['rmse_y_mean']:8.3f} +/- {r['rmse_y_std']:6.3f} m"
            )

    # -------------------- GRAPHS --------------------

    plot_learning_curve(summary, RESULTS_DIR / "stage7_learning_curve.png")
    plot_stability(summary, RESULTS_DIR / "stage7_stability.png")

    condition, x_classical, y_classical, sweeps, error_curve = trajectory_experiment(
        pool, test
    )
    error_curve.to_csv(RESULTS_DIR / "stage7_trajectory_error.csv", index=False)

    print("\n--- whole-trajectory reconstruction "
          f"(mean radial error over {SWEEP_CONDITIONS} unseen conditions) ---")
    for _, r in error_curve.iterrows():
        print(f"  n={int(r['n_train']):>6,}  mean radial error = {r['mean_error']:6.2f} m")

    plot_trajectory_by_datasize(
        x_classical, y_classical, sweeps,
        condition["v0"], condition["theta"], condition["y0"],
        error_curve,
        RESULTS_DIR / "stage7_trajectory_by_datasize.png",
    )

    print("\nSaved:")
    for name in [
        "stage7_learning_curve.csv",
        "stage7_learning_curve_summary.csv",
        "stage7_trajectory_error.csv",
        "stage7_learning_curve.png",
        "stage7_stability.png",
        "stage7_trajectory_by_datasize.png",
    ]:
        print(f"  results/{name}")
